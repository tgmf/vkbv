// Generates src/sim/exp-table.ts: EXP[k] = round(65536 · e^(−k/100)), k = 0..1200 (spec 03 §1.1).
// Run once with `npx tsx scripts/gen-exp-table.ts`; the output is committed. This is the only
// place in the project allowed to compute an exponential.
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

const values = Array.from({ length: 1201 }, (_, k) => Math.round(65536 * Math.exp(-k / 100)));

const rows: string[] = [];
for (let i = 0; i < values.length; i += 16)
  rows.push('  ' + values.slice(i, i + 16).join(', ') + ',');

const source = `// Generated by scripts/gen-exp-table.ts. Do not edit by hand.
/** EXP[k] = round(65536 · e^(−k/100)) for k = 0..1200 (spec 03 §1.1). */
export const EXP: readonly number[] = [
${rows.join('\n')}
];
`;

writeFileSync(join(import.meta.dirname, '..', 'src', 'sim', 'exp-table.ts'), source);
console.log(`wrote ${values.length} values`);
