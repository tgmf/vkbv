// Generates src/sim/phi-table.ts: PHI[k] = round(1 000 000 · Φ(k/100)), k = 0..400, Φ the standard
// normal CDF (spec 03 §13.7). Run once with `npx tsx scripts/gen-phi-table.ts`; the output is
// committed. Nothing computes Φ at runtime.
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

/** Φ(x) for x >= 0 by the Taylor series of the error function; exact to ~1e-15 for x <= 4. */
function phi(x: number): number {
  const z = x / Math.SQRT2;
  // erf(z) = 2/√π Σ (−1)^n z^(2n+1) / (n! (2n+1))
  let sum = 0;
  let termValue = z;
  for (let n = 0; n < 200; n++) {
    sum += termValue / (2 * n + 1);
    termValue *= (-z * z) / (n + 1);
  }
  return 0.5 * (1 + (2 / Math.sqrt(Math.PI)) * sum);
}

const values = Array.from({ length: 401 }, (_, k) => Math.round(1_000_000 * phi(k / 100)));

const rows: string[] = [];
for (let i = 0; i < values.length; i += 12)
  rows.push('  ' + values.slice(i, i + 12).join(', ') + ',');

const source = `// Generated by scripts/gen-phi-table.ts. Do not edit by hand.
/** PHI[k] = round(1 000 000 · Φ(k/100)) for k = 0..400, Φ the standard normal CDF (spec 03 §13.7). */
export const PHI: readonly number[] = [
${rows.join('\n')}
];
`;

writeFileSync(join(import.meta.dirname, '..', 'src', 'sim', 'phi-table.ts'), source);
console.log(`wrote ${values.length} values`);
